package dev.alan.mineworld.client;

import com.mojang.blaze3d.vertex.PoseStack;
import dev.alan.mineworld.MineWorldMod;
import dev.alan.mineworld.mob.Mobs;
import net.minecraft.client.model.ambient.BatModel;
import net.minecraft.client.model.geom.ModelLayers;
import net.minecraft.client.model.monster.slime.SlimeModel;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.entity.AbstractCubeMobRenderer;
import net.minecraft.client.renderer.entity.BatRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.EntityRenderers;
import net.minecraft.client.renderer.entity.IronGolemRenderer;
import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.client.renderer.entity.SilverfishRenderer;
import net.minecraft.client.renderer.entity.layers.EyesLayer;
import net.minecraft.client.renderer.entity.layers.RenderLayer;
import net.minecraft.client.renderer.entity.state.BatRenderState;
import net.minecraft.client.renderer.entity.state.IronGolemRenderState;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.client.renderer.entity.state.SlimeRenderState;
import net.minecraft.client.renderer.rendertype.RenderType;
import net.minecraft.client.renderer.rendertype.RenderTypes;
import net.minecraft.resources.Identifier;
import net.minecraft.world.entity.monster.cubemob.Slime;

/** The mine world creatures reuse the vanilla models with their own textures (generated by scripts/gen_mineworld_data.py). */
final class MobRenderers {
    private MobRenderers() {}

    private static Identifier texture(String name) { return MineWorldMod.id("textures/entity/" + name + ".png"); }

    static void register() {
        EntityRenderers.register(Mobs.GLOW_BAT, GlowBatRenderer::new);
        EntityRenderers.register(Mobs.GEM_SLIME, GemSlimeRenderer::new);
        EntityRenderers.register(Mobs.ORE_GOLEM, OreGolemRenderer::new);
        EntityRenderers.register(Mobs.ORE_WORM, OreWormRenderer::new);
    }

    /** A bat whose glow layer is drawn full bright, like spider eyes, so it shows up in the pitch dark. */
    static final class GlowBatRenderer extends BatRenderer {
        private static final Identifier TEXTURE = texture("glow_bat");
        private static final RenderType GLOW = RenderTypes.eyes(texture("glow_bat_glow"));

        GlowBatRenderer(EntityRendererProvider.Context context) {
            super(context);
            this.addLayer(new EyesLayer<BatRenderState, BatModel>(this) {
                @Override public RenderType renderType() { return GLOW; }
            });
        }

        @Override public Identifier getTextureLocation(BatRenderState state) { return TEXTURE; }
    }

    /** Same as the vanilla slime renderer, but both the inner cube and the translucent shell use the gem texture. */
    static final class GemSlimeRenderer extends AbstractCubeMobRenderer<Slime, SlimeRenderState, SlimeModel> {
        private static final Identifier TEXTURE = texture("gem_slime");

        GemSlimeRenderer(EntityRendererProvider.Context context) {
            super(context, new SlimeModel(context.bakeLayer(ModelLayers.SLIME)));
            SlimeModel outer = new SlimeModel(context.getModelSet().bakeLayer(ModelLayers.SLIME_OUTER));
            this.addLayer(new RenderLayer<SlimeRenderState, SlimeModel>(this) {
                @Override public void submit(PoseStack poseStack, SubmitNodeCollector collector, int lightCoords, SlimeRenderState state,
                                             float yRot, float xRot) {
                    if (state.isInvisible) return;
                    collector.order(1).submitModel(outer, state, poseStack, RenderTypes.entityTranslucent(TEXTURE), lightCoords,
                        LivingEntityRenderer.getOverlayCoords(state, 0.0F), state.outlineColor);
                }
            });
        }

        @Override protected void scale(SlimeRenderState state, PoseStack poseStack) {
            this.downscaleSlightly(poseStack);
            super.scale(state, poseStack);
        }

        @Override public Identifier getTextureLocation(SlimeRenderState state) { return TEXTURE; }

        @Override public SlimeRenderState createRenderState() { return new SlimeRenderState(); }
    }

    static final class OreGolemRenderer extends IronGolemRenderer {
        private static final Identifier TEXTURE = texture("ore_golem");

        OreGolemRenderer(EntityRendererProvider.Context context) { super(context); }

        @Override public Identifier getTextureLocation(IronGolemRenderState state) { return TEXTURE; }
    }

    static final class OreWormRenderer extends SilverfishRenderer {
        private static final Identifier TEXTURE = texture("ore_worm");

        OreWormRenderer(EntityRendererProvider.Context context) { super(context); }

        @Override public Identifier getTextureLocation(LivingEntityRenderState state) { return TEXTURE; }
    }
}
