package dev.alan.mineworld.test;

import dev.alan.mineworld.DynamicLevels;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import net.fabricmc.fabric.api.client.gametest.v1.FabricClientGameTest;
import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.chunk.status.ChunkStatus;

/**
 * Timing for the mine world, off by default: {@code MINEWORLD_BENCH=1 ./gradlew :mods:mineworld:runClientGameTest}. Prints how long creating
 * a world takes (the hitch when a player first enters it) and how long its chunks take to generate, split into the terrain pass and the
 * rest (features: ores, caves' decorations, dungeons, then lighting and finishing).
 */
public final class MineWorldBenchGameTest implements FabricClientGameTest {
    private static final int CHUNKS = 60;

    @Override public void runTest(ClientGameTestContext context) {
        if (!"1".equals(System.getenv("MINEWORLD_BENCH"))) return;
        try (TestSingleplayerContext world = context.worldBuilder().adjustSettings(s -> s.setGenerateStructures(true)).create()) {
            var server = world.getServer();
            world.getConnection().waitForChunksRender();
            for (String command : new String[] {"gamerule spawn_mobs false", "fill -8 119 -8 8 119 8 minecraft:stone", "fill -8 120 -8 8 130 8 minecraft:air", "tp @p 0 120 0"})
                server.runCommand(command);
            // A world entered cold: its room is built the moment the player arrives, so the server thread generates the chunks itself.
            String cold = server.computeOnServer(s -> dev.alan.mineworld.MineWorldData.get(s).createWorld());
            long coldNanos = server.computeOnServer(s -> {
                long start = System.nanoTime();
                DynamicLevels.ensure(s, cold);
                return System.nanoTime() - start;
            });
            System.out.println("[mine-bench] entering a world cold (create, generate the room chunks, build the room): " + coldNanos / 1_000_000 + " ms");

            // The same world after the four seconds of the sneak countdown, during which the chunks generate on the worker threads.
            String id = server.computeOnServer(s -> dev.alan.mineworld.MineWorldData.get(s).createWorld());
            long prewarmNanos = server.computeOnServer(s -> {
                long start = System.nanoTime();
                DynamicLevels.prewarm(s, id);
                return System.nanoTime() - start;
            });
            context.waitTicks(80);
            long warmNanos = server.computeOnServer(s -> {
                long start = System.nanoTime();
                DynamicLevels.ensure(s, id);
                return System.nanoTime() - start;
            });
            System.out.println("[mine-bench] entering a world after the countdown: starting it took " + prewarmNanos / 1_000_000 + " ms, arriving took "
                + warmNanos / 1_000_000 + " ms");

            // The tunnel, slice by slice as the server does it, with a player there so the chunks are loaded: the cost of the busiest tick.
            server.runOnServer(s -> s.getPlayerList().getPlayers().get(0).teleportTo(s.getLevel(DynamicLevels.key(id)), 0.5, 128, 1.5, java.util.Set.of(), 180, 0, false));
            long[] tick = new long[1];
            int ticks = 0;
            while (ticks < 400 && !server.computeOnServer(s -> dev.alan.mineworld.MineWorldData.get(s).world(id).tunnelNext() == dev.alan.mineworld.MineWorldData.WorldInfo.TUNNEL_FINISHED)) {
                tick[0] = Math.max(tick[0], server.computeOnServer(s -> {
                    long start = System.nanoTime();
                    DynamicLevels.tickTunnels(s);
                    return System.nanoTime() - start;
                }));
                context.waitTicks(1);
                ticks++;
            }
            System.out.println("[mine-bench] tunnel dug in steps: " + ticks + " ticks, busiest step " + DynamicLevels.busiestTunnelStepNanos() / 1_000_000.0 + " ms"
                + (ticks >= 400 ? " (not finished)" : ""));
            // Chunks well away from the tunnel and the city, so none of them was generated by the room.
            List<Long> terrain = new ArrayList<>(), features = new ArrayList<>(), rest = new ArrayList<>();
            server.runOnServer(s -> {
                ServerLevel level = s.getLevel(DynamicLevels.key(id));
                for (int i = 0; i < CHUNKS; i++) {
                    int cx = 40 + i % 10, cz = -60 + i / 10;
                    long t0 = System.nanoTime();
                    level.getChunk(cx, cz, ChunkStatus.TERRAIN);
                    long t1 = System.nanoTime();
                    level.getChunk(cx, cz, ChunkStatus.FEATURES);
                    long t2 = System.nanoTime();
                    level.getChunk(cx, cz, ChunkStatus.FULL);
                    long t3 = System.nanoTime();
                    terrain.add(t1 - t0);
                    features.add(t2 - t1);
                    rest.add(t3 - t2);
                }
            });
            report("terrain (structure starts, biomes, noise terrain)", terrain);
            report("features (ores, decorations, dungeons)", features);
            report("light and finishing", rest);
            List<Long> total = new ArrayList<>();
            for (int i = 0; i < terrain.size(); i++) total.add(terrain.get(i) + features.get(i) + rest.get(i));
            report("whole chunk", total);
        }
    }

    private static void report(String what, List<Long> nanos) {
        List<Long> sorted = new ArrayList<>(nanos);
        Collections.sort(sorted);
        double mean = sorted.stream().mapToLong(Long::longValue).average().orElse(0) / 1e6;
        System.out.printf("[mine-bench] %s over %d chunks: mean %.1f ms, median %.1f ms, p95 %.1f ms, max %.1f ms%n", what, sorted.size(), mean,
            sorted.get(sorted.size() / 2) / 1e6, sorted.get((int) (sorted.size() * 0.95)) / 1e6, sorted.getLast() / 1e6);
    }
}
